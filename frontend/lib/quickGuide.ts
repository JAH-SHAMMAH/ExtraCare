export function searchTopics(q: string): GuideTopic[] {
  const s = q.trim().toLowerCase();
  if (!s) return GUIDE_TOPICS;
  return GUIDE_TOPICS.filter((t) =>
    [t.title, t.summary, t.category, ...t.steps, ...(t.tips ?? [])].join(" ").toLowerCase().includes(s),
  );
}
